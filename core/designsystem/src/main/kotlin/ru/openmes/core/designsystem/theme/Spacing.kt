package ru.openmes.core.designsystem.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Шкала отступов.
 *
 * Все значения кратны [step] — это базовый ритм интерфейса. Числа означают
 * не «на глаз», а расстояние между элементами: [xs] — внутри группы,
 * [s] — между строками списка, [m] — внутри карточки, [l] — между карточками,
 * [xl] — между смысловыми блоками экрана.
 *
 * Правило: между родственными элементами — шаг меньше, между несвязанными —
 * больше. Размеры элементов (иконки, аватары, значки) шкалой не задаются:
 * там важны конкретные числа, а не ритм.
 */
object Spacing {
    /** Базовый шаг шкалы. Всё, что не [step], — исключение, и оно должно быть обосновано. */
    val step: Dp = 4.dp

    /** 2 dp — между буквой и её подписью. */
    val xxs: Dp = step / 2

    /** 4 dp — минимальный отступ, внутри одной группы. */
    val xs: Dp = step

    /** 8 dp — между строками списка и элементами группы. */
    val s: Dp = step * 2

    /** 12 dp — внутри карточки, от её края до содержимого. */
    val m: Dp = step * 3

    /** 16 dp — между карточками, горизонтальные поля экрана. */
    val l: Dp = step * 4

    /** 24 dp — между смысловыми блоками экрана. */
    val xl: Dp = step * 6

    /** 32 dp — крупные разделители секций. */
    val xxl: Dp = step * 8
}
